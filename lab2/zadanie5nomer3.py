"""Дан список слов. Создать множество из слов, длина которых больше 5
символов"""

slova = ["лук", "капуста", "молоко", "яйца", "баклажан", "кабачок", "помидор",
         "свёкла", "помидор", "мясо", "лимон", "лайм"]
