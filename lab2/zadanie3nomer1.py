"""Создать словарь с именами студентов и их оценками, вывести средний балл"""

zhurnal = {
    "Иванов": 3,
    "Петров": 5,
    "Андреев": 4,
    "Сергеев": 5,
    "Романов": 3
    }
print("Журнал:")
for i, j in zhurnal.items():
    print("Фамилия: ", i, " Оценка: ", j)
srednee = sum(zhurnal.values()) / len(zhurnal)
print("Средний балл: ", srednee)